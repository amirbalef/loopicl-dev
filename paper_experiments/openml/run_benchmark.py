"""Benchmark runner — no tabarena, no autogluon dependency.

Dataset modes (--dataset)
    quick               3 tasks, fold 0/repeat 0
    tabarena-lite       All 51 tasks, fold 0/repeat 0
    tabarena            All 51 tasks, full fold × repeat protocol
    tabarena-cls        Classification tasks only, full fold × repeat protocol
    tabarena-cls-lite   Classification tasks only, fold 0/repeat 0
    dev-cls             Development classification datasets, full fold × repeat protocol
    dev-cls-folds3      Development classification datasets, folds 0–2 of repeat 0
    dev-cls-lite        Development classification datasets, fold 0/repeat 0
    dev-reg             Development regression datasets, full fold × repeat protocol
    dev-reg-lite        Development regression datasets, fold 0/repeat 0
    synthetic-priors    Synthetic datasets generated by TabICL v2's prior (needs --prior-dir)

Usage examples
    uv run benchmark_eval/openml/run_benchmark.py --dataset quick
    uv run benchmark_eval/openml/run_benchmark.py --dataset tabarena-lite --models TabPFN-v2.5,TabICL-v2
    uv run benchmark_eval/openml/run_benchmark.py --dataset tabarena-cls --models TabPFN-v2.5
    uv run benchmark_eval/openml/run_benchmark.py --dataset tabarena-lite --config TabPFN_v2_5_ri_bc
    uv run benchmark_eval/openml/run_benchmark.py --dataset dev-cls-lite --models TabPFN-v3
    uv run benchmark_eval/openml/run_benchmark.py --dataset dev-reg-lite --models TabPFN-v3

    # Synthetic prior workflow (generate first, then benchmark):
    uv run benchmark_eval/openml/generate_synthetic_priors.py --n-datasets 100
    uv run benchmark_eval/openml/run_benchmark.py --dataset synthetic-priors \\
        --prior-dir results/synthetic_priors/tabicl_v2 --models TabICL-v2,LoopICL

Output
    results/<dataset>/
        <model_name>/results.csv
    Run leaderboard.py on the results dir to build leaderboard.csv.
"""
