# ---------------------------------------------------------------------------
# Development-dataset task resolver
# ---------------------------------------------------------------------------


def get_dev_task_ids(task_type: str) -> list[int]:
    """Return OpenML task IDs for the development datasets.

    Parameters
    ----------
    task_type : "cls" | "reg"
        Which development split to resolve.

    Looks up OpenML tasks whose dataset ID matches one of the entries in
    datasets/dev_datasets.py, keeping the numerically smallest task ID per
    dataset (the oldest / canonical supervised task).
    """
    import openml
    from datasets.dev_datasets import (
        CLASSIFICATION_DATASET_IDS,
        REGRESSION_DATASET_IDS,
        PREFERRED_TASK_IDS,
    )

    if task_type == "cls":
        dataset_ids = set(CLASSIFICATION_DATASET_IDS.values())
        task_type_id = openml.tasks.TaskType.SUPERVISED_CLASSIFICATION
    else:
        dataset_ids = set(REGRESSION_DATASET_IDS.values())
        task_type_id = openml.tasks.TaskType.SUPERVISED_REGRESSION

    df = openml.tasks.list_tasks(task_type=task_type_id, output_format="dataframe")
    df = df[df["did"].isin(dataset_ids)]

    # One task per dataset: keep the smallest (oldest) task ID, then apply overrides
    # for datasets where the oldest task doesn't use 10-fold CV.
    df_deduped = df.sort_values("tid").drop_duplicates(subset="did", keep="first")
    task_ids = [
        PREFERRED_TASK_IDS.get(int(row["did"]), int(row["tid"]))
        for _, row in df_deduped.iterrows()
    ]
    return task_ids


# ---------------------------------------------------------------------------
# Config loader
# ---------------------------------------------------------------------------


def load_configs(name: str) -> list[dict]:
    """Load benchmark_eval/openml/configs/<name>.py and return a list of config dicts.

    Files may export either:
    - ``CONFIGS``: a list of dicts, each with a ``"name"`` key (preferred), or
    - ``CONFIG``:  a single dict with a ``"name"`` key (legacy/single-variant).
    """
    import importlib.util
    path = Path(__file__).parent / "configs" / f"{name.replace('.', '/')}.py"
    if not path.exists():
        available = [p.stem for p in path.parent.glob("*.py") if p.stem != "__init__"]
        raise FileNotFoundError(
            f"Config '{name}' not found at {path}. Available: {available}"
        )
    spec = importlib.util.spec_from_file_location(name, path)
    mod  = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    if hasattr(mod, "CONFIGS"):
        return mod.CONFIGS
    cfg = mod.CONFIG
    if "name" not in cfg:
        cfg = {**cfg, "name": name}
    return [cfg]


