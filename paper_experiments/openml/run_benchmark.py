def build_experiments(
    model_names: list[str],
    configs: list[str] | None = None,
) -> list:
    from runner import Experiment
    from models.dummy_model import DummyModel
    from models.tabicl_v2_model import TabICLv2Model
    from models.tabpfn_v3_model import TabPFNv3Model
    from models.iris_model import IrisModel
    from models.ricotta_model import (
        RicottaModel,
        RicottaNormHistModel,
        RicottaNormHistNoShiftModel,
        RicottaNormHistChunkModel,
        RicottaSandwichModel,
        PairedColRicottaModel,
        LabelPairedRicottaModel,
        RicottaUnrolledModel,
        QuadColRicottaModel,
        TabFMEmbedRicottaModel,
        FeatCircShiftRicottaModel,
        RicottaEarlyExitModel,
    )
    from models.early_exit_model import EarlyExitIrisModel

    _local_cls: dict[str, type] = {
        "Dummy":                  DummyModel,
        "TabICL-v2":              TabICLv2Model,
        "TabPFN-v3":              TabPFNv3Model,
        "Iris":                   IrisModel,
        "IrisEE":                 EarlyExitIrisModel,
        "LoopICL":                RicottaModel,
        "RicottaNormHist":        RicottaNormHistModel,
        "RicottaNormHistNoShift": RicottaNormHistNoShiftModel,
        "RicottaNormHistChunk":   RicottaNormHistChunkModel,
        "RicottaSandwich":        RicottaSandwichModel,
        "PairedColRicotta":       PairedColRicottaModel,
        "LabelPairedRicotta":     LabelPairedRicottaModel,
        "RicottaUnrolled":        RicottaUnrolledModel,
        "QuadColRicotta":         QuadColRicottaModel,
        "TabFMEmbedRicotta":      TabFMEmbedRicottaModel,
        "FeatCircShiftRicotta":   FeatCircShiftRicottaModel,
        "LoopICLEarlyExit":       RicottaEarlyExitModel,
    }

    experiments = []

    for name in model_names:
        if name not in _local_cls:
            print(f"  [skip] Unknown model '{name}'. Available: {sorted(_local_cls)}")
            continue
        cls = _local_cls[name]
        experiments.append(Experiment(
            name=name,
            factory=lambda pt, c=cls: c(),
        ))

    # Config-file variants
    for cfg_file in (configs or []):
        try:
            cfgs = load_configs(cfg_file)
        except FileNotFoundError as exc:
            print(f"  [skip] {exc}")
            continue
        for cfg in cfgs:
            cfg_name   = cfg.get("name", cfg_file)
            model_name = cfg.get("model")
            exp_type   = cfg.get("exp_type")
            if model_name in _local_cls:
                cls = _local_cls[model_name]
                _runner_keys = ("name", "model", "interface", "exp_type", "folder",
                                "subsample_train", "subsample_test", "save_mode")
                kwargs = {k: v for k, v in cfg.items() if k not in _runner_keys}
                experiments.append(Experiment(
                    name=cfg_name,
                    factory=lambda pt, c=cls, kw=kwargs: c(**kw),
                    exp_type=exp_type,
                    folder=cfg.get("folder"),
                    subsample_train=cfg.get("subsample_train"),
                    subsample_test=cfg.get("subsample_test"),
                    save_mode=cfg.get("save_mode", "per_task"),
                ))
            else:
                print(f"  [skip] config '{cfg_name}': model '{model_name}' not in local models")

    return experiments


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run tabular benchmark (no tabarena/autogluon)."
    )
    parser.add_argument(
        "--dataset",
        default="tabarena-lite",
        choices=list(_DATASET_PRESETS),
        help="Benchmark mode. (default: tabarena-lite)",
    )
    parser.add_argument(
        "--tasks",
        default=None,
        metavar="ID,ID,...",
        help="Comma-separated OpenML task IDs (overrides --dataset task selection).",
    )
    parser.add_argument(
        "--models",
        default=None,
        metavar="NAME,NAME,...",
        help=(
            f"Comma-separated model names. "
            f"Default: {','.join(DEFAULT_MODEL_NAMES)}."
        ),
    )
    parser.add_argument(
        "--all-models",
        action="store_true",
        help="Run all available models.",
    )
    parser.add_argument(
        "--output-dir",
        default=None,
        help="Override default output directory.",
    )
    parser.add_argument(
        "--config",
        default=None,
        metavar="NAME,NAME,...",
        help=(
            "Comma-separated config names from benchmark_eval/openml/configs/*.py. "
            "Each config defines a RepInject experiment (model, strategy, layers). "
            "Example: --config TabPFN_v2_5_ri_bc"
        ),
    )
    parser.add_argument(
        "--prior-dir",
        default=None,
        metavar="DIR",
        help=(
            "Directory of pre-generated synthetic prior datasets "
            "(required when --dataset synthetic-priors). "
            "Default: results/synthetic_priors/tabicl_v2"
        ),
    )
    parser.add_argument(
        "--raise-on-failure",
        action="store_true",
        default=False,
    )
    return parser.parse_args()


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def run(args: argparse.Namespace) -> None:
    _here = Path(__file__).parent.resolve()
    if str(_here) not in sys.path:
        sys.path.insert(0, str(_here))

    from runner import run_experiments, run_synthetic_experiments

    tasks_mode, repetitions = _DATASET_PRESETS[args.dataset]

    # Output directory
    configs = (
        [c.strip() for c in args.config.split(",") if c.strip()]
        if args.config else []
    )
    if args.output_dir is not None:
        base_dir = Path(args.output_dir)
    elif configs:
        base_dir = Path("results/experiments") / args.dataset / configs[0]
    else:
        base_dir = Path("results/experiments") / args.dataset
    base_dir.mkdir(parents=True, exist_ok=True)

    # Synthetic-prior mode — bypass OpenML task loading entirely
    if tasks_mode == "synthetic":
        prior_dir = Path(
            args.prior_dir
            if args.prior_dir is not None
            else "results/synthetic_priors/tabicl_v2"
        )
        if not prior_dir.exists():
            print(
                f"[ERROR] Prior directory not found: {prior_dir}\n"
                f"  Generate priors first:\n"
                f"    uv run benchmark_eval/openml/generate_synthetic_priors.py "
                f"--output {prior_dir}"
            )
            return

        if args.all_models:
            model_names = ALL_MODEL_NAMES
        elif args.models:
            model_names = [m.strip() for m in args.models.split(",") if m.strip()]
        elif args.config:
            model_names = []
        else:
            model_names = DEFAULT_MODEL_NAMES

        print(f"\nBuilding experiments for: {model_names}")
        experiments = build_experiments(model_names, configs=configs)
        if not experiments:
            print("No valid experiments. Exiting.")
            return

        print(f"Valid: {[e.name for e in experiments]}")
        print(f"Prior dir: {prior_dir}")
        print(f"Output: {base_dir}\n")

        run_synthetic_experiments(
            experiments=experiments,
            prior_dir=prior_dir,
            output_dir=base_dir,
            raise_on_failure=args.raise_on_failure,
        )

        print(f"\nDone. Results in: {base_dir}")
        print(f"Build leaderboard: uv run benchmark_eval/openml/leaderboard.py {base_dir}")
        return

    # Task selection
    if args.tasks is not None:
        tasks = [int(t.strip()) for t in args.tasks.split(",") if t.strip()]
        repetitions = "lite"
        print(f"[custom] {len(tasks)} tasks, fold 0/repeat 0.")
    elif tasks_mode == "quick":
        tasks = QUICK_TASKS
        print(f"[quick] {len(tasks)} tasks, fold 0/repeat 0.")
    elif tasks_mode == "cls":
        try:
            import openml
            all_task_ids = list(openml.study.get_suite("tabarena-v0.1").tasks)
            tasks_df = openml.tasks.list_tasks(task_id=all_task_ids, output_format="dataframe")
            tasks = tasks_df[tasks_df["task_type"] == "Supervised Classification"]["tid"].tolist()
        except Exception as e:
            print(f"[WARNING] OpenML unavailable ({e}), falling back to hardcoded tabarena classification task IDs.")
            tasks = TABARENA_CLS_TASKS
        print(f"[{args.dataset}] {len(tasks)} classification tasks, repetitions={repetitions}.")
    elif tasks_mode in ("dev-cls", "dev-reg"):
        try:
            tasks = get_dev_task_ids("cls" if tasks_mode == "dev-cls" else "reg")
        except Exception as e:
            print(f"[WARNING] Failed to resolve development task IDs ({e}).")
            return
        label = "classification" if tasks_mode == "dev-cls" else "regression"
        print(f"[{args.dataset}] {len(tasks)} development {label} tasks, repetitions={repetitions}.")
    else:
        try:
            import openml
            tasks = list(openml.study.get_suite("tabarena-v0.1").tasks)
        except Exception as e:
            print(f"[WARNING] OpenML unavailable ({e}).")
            return
        print(f"[{args.dataset}] {len(tasks)} tasks, repetitions={repetitions}.")

    # Model selection
    if args.all_models:
        model_names = ALL_MODEL_NAMES
    elif args.models:
        model_names = [m.strip() for m in args.models.split(",") if m.strip()]
    elif args.config:
        model_names = []  # config-only run
    else:
        model_names = DEFAULT_MODEL_NAMES

    print(f"\nBuilding experiments for: {model_names}")
    if configs:
        print(f"Configs: {configs}")

    experiments = build_experiments(model_names, configs=configs)
    if not experiments:
        print("No valid experiments. Exiting.")
        return

    print(f"Valid: {[e.name for e in experiments]}")
    print(f"Output: {base_dir}\n")

    run_experiments(
        experiments=experiments,
        tasks=tasks,
        output_dir=base_dir,
        repetitions=repetitions,
        raise_on_failure=args.raise_on_failure,
    )

    print(f"\nDone. Results in: {base_dir}")
    print(f"Build leaderboard: uv run benchmark_eval/openml/leaderboard.py {base_dir}")


if __name__ == "__main__":
    run(parse_args())
